#!/usr/bin/env python3
"""gen_log_vectors.py - the log link's test vectors, generated from the record (BT3, R2).

Reads 02-PROJECTS/02-electrical/data/log_channels.csv, log_link.csv and params.csv and
writes log_vectors.h beside this script: every log_channels row's id and byte width, their
sum, params log_thin_bytes_per_s and radio_uart_baud, and from log_link the UUIDs, the
device name, every opcode and frame type, the tier / state / error codes, the DATA size and
the timings. test_loglink.cpp includes it next to ../display-unit/firmware/du/log_link.h and ../display-unit/firmware/du/log_store.h
and holds every constant there to it - a channel, opcode or UUID that moves in the record
fails the suite until the firmware follows. The record is the master; this file is build
output (not versioned).

A token the record names that this script cannot map to a firmware name is an error (exit 1).
Stdlib only, Python 3.9.
"""
import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parents[1] / "data"
OUT = HERE / "log_vectors.h"

CODES = {   # the words log_link uses -> the firmware's macro suffix
    "tier": {"summary": "TIER_SUMMARY", "thin": "TIER_THIN", "full": "TIER_FULL"},
    "state": {"idle": "S_IDLE", "listing": "S_LISTING", "sending": "S_SENDING", "done": "S_DONE",
              "error": "S_ERROR"},
    "err": {"none": "E_NONE", "bad opcode": "E_OPCODE", "no such drive or tier": "E_NO_DRIVE",
            "no card": "E_NO_CARD", "busy": "E_BUSY", "aborted": "E_ABORTED", "teensy silent": "E_SILENT"},
}
CHARS = {"LL03": "INFO", "LL04": "DRIVES", "LL05": "CONTROL", "LL09": "DATA", "LL10": "STATUS"}


def read(name):
    with open(DATA / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def codes(text, field, kind, errors, row):
    m = re.search(field + r" u8 \(([^)]*)\)", text)
    if not m:
        errors.append(f"{row}: no '{field} u8 (...)' list")
        return []
    out = []
    for part in m.group(1).split(","):
        num, _, word = part.strip().partition(" ")
        word = word.strip().lower()
        if word not in CODES[kind]:
            errors.append(f"{row}: no firmware name for {kind} '{word}' - add it to log_link.h and gen_log_vectors.py")
            continue
        out.append(f"#define V_LL_{CODES[kind][word]:<14} {int(num)}")
    return out


def main() -> int:
    errors = []
    lines = ["/* log_vectors.h - generated by gen_log_vectors.py from log_channels.csv, log_link.csv and",
             " * params.csv (the record is the master, D-493 / D-494). Do not edit; run.sh rewrites it. */",
             "#ifndef LOG_VECTORS_H", "#define LOG_VECTORS_H", ""]

    chans = sorted(read("log_channels.csv"), key=lambda r: r["id"])
    widths = []
    for i, r in enumerate(chans, 1):
        if r["id"] != f"LC{i:02d}":
            errors.append(f"log_channels: expected LC{i:02d}, found {r['id']} - the record skips or repeats a row")
        if not r["bytes"].strip().isdigit():
            errors.append(f"{r['id']}: bytes '{r['bytes']}' is not a number")
            continue
        widths.append(int(r["bytes"]))
    lines.append(f"#define V_LOG_CHANNELS {len(chans)}")
    lines.append(f"#define V_LOG_THIN_SUM {sum(widths)}")
    lines.append("static const unsigned char V_LOG_CH_BYTES[] = { " + ", ".join(map(str, widths)) + " };")
    lines.append("")

    params = {r["key"]: r["value"] for r in read("params.csv")}
    for key, name in (("log_thin_bytes_per_s", "V_PARAM_THIN"), ("radio_uart_baud", "V_PARAM_BAUD")):
        if not params.get(key, "").strip().isdigit():
            errors.append(f"params {key}: missing or not a number")
            continue
        lines.append(f"#define {name:<16} {params[key].strip()}u")
    lines.append("")

    ll = {r["id"]: r for r in read("log_link.csv")}
    svc = re.search(r"([0-9a-f]{8})-([0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})", ll["LL01"]["payload"])
    name = re.search(r"Name (\S+?);", ll["LL01"]["payload"])
    if not svc or not name:
        errors.append("LL01: no service UUID or device name")
    else:
        lines.append(f'#define V_LL_UUID_SERVICE "{svc.group(0)}"')
        lines.append(f'#define V_LL_DEVICE_NAME  "{name.group(1)}"')
        for row, char in CHARS.items():
            m = re.search(r"([0-9a-f]{8})-\.\.\.", ll[row]["note"])
            if not m:
                errors.append(f"{row}: no characteristic UUID in the note")
                continue
            lines.append(f'#define V_LL_UUID_{char:<8} "{m.group(1)}-{svc.group(2)}"')
    lines.append("")

    ops = {}   # the phone opcodes (LL06-LL08) are named again in LL12: they must agree
    for row in ("LL06", "LL07", "LL08", "LL12", "LL13"):
        for op, val in re.findall(r"\b([A-Z][A-Z_]+) 0x([0-9A-Fa-f]{2})\b", ll[row]["item"]):
            if op in ops and ops[op] != val.upper():
                errors.append(f"{row}: {op} is 0x{val} here and 0x{ops[op]} in an earlier row")
            ops.setdefault(op, val.upper())
    lines += [f"#define V_LL_{op:<14} 0x{val}" for op, val in ops.items()]
    lines.append("")

    lines += codes(ll["LL07"]["payload"], "tier", "tier", errors, "LL07")
    lines += codes(ll["LL10"]["payload"], "state", "state", errors, "LL10")
    lines += codes(ll["LL10"]["payload"], "err", "err", errors, "LL10")
    lines.append("")

    nums = [
        ("V_LL_DATA_MAX", "LL13", "payload", r"up to (\d+) bytes"),
        ("V_LL_TIMEOUT_S", "LL14", "payload", r"no CREDIT for (\d+) s"),
        ("V_LL_SILENT_S", "LL14", "payload", r"no DATA for (\d+) s"),
        ("V_LL_PAIR_S", "LL02", "payload", r"pairing mode for (\d+) s"),
        ("V_LL_TIME_SLACK_S", "LL08", "payload", r"more than (\d+) s"),
        ("V_LL_PROTOCOL", "LL03", "payload", r"protocol u8 \((\d+)\)"),
        ("V_LL_MTU", "LL09", "note", r"MTU (\d+) or more"),
    ]
    for macro, row, col, rx in nums:
        m = re.search(rx, ll[row][col])
        if not m:
            errors.append(f"{row}: cannot read {macro} ('{rx}')")
            continue
        lines.append(f"#define {macro:<18} {m.group(1)}")

    lines += ["", "#endif", ""]
    if errors:
        for e in errors:
            print("gen_log_vectors:", e)
        return 1
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"gen_log_vectors: {OUT.name} written, {sum(1 for l in lines if l.startswith('#define'))} vectors")
    return 0


if __name__ == "__main__":
    sys.exit(main())
