#!/usr/bin/env python3
"""
gen.py — render every derived pin/cavity document from the two data tables.

    02-HARNESS/data/pmu_pins.csv     one row per PMU cavity (39 + the stud)
    02-HARNESS/data/connectors.csv   one row per leg / door / drop cavity
    02-HARNESS/data/housings.csv     one row per housing

Produces (full files):
    02-HARNESS/PIN-MAP.md
    02-HARNESS/CAVITY-STATE.md
    02-HARNESS/diagrams/L1.svg … L4.svg, drops.svg, sill.svg
    03-MODULES/firmware/pmu_sim/channels.h

Refreshes marked blocks inside (everything outside the markers is hand-written):
    01-DESIGN/SPEC.md              <!-- gen:pins --> … <!-- /gen:pins -->
    01-DESIGN/CHANNEL-SCHEDULE.md  <!-- gen:schedule --> … <!-- /gen:schedule -->
    04-BUILD/CUT-LIST.md           <!-- gen:cutlist --> … <!-- /gen:cutlist -->
    02-HARNESS/CONNECTORS.md       <!-- gen:housings --> … <!-- /gen:housings -->

Usage:  python gen.py            (run from anywhere; paths are resolved from this file)
        python gen.py --check    (exit 1 if any output would change — used by check.py)

Edit the CSVs, never the generated tables.  Rule R3: one owner per fact — the
owner of every pin, cavity, colour and estimate is the CSV.
"""
import csv, os, sys, re, io, collections

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.normpath(os.path.join(HERE, "..", ".."))
DATA = os.path.join(PROJ, "02-HARNESS", "data")
CHECK = "--check" in sys.argv
changed = []

def read(name):
    with open(os.path.join(DATA, name), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))

pins = read("pmu_pins.csv")
cavs = read("connectors.csv")
housings = read("housings.csv")

STAMP = "*Generated by `05-PROCESS/tools/gen.py` from `02-HARNESS/data/*.csv` — edit the CSV, not this table.*"

def emit(relpath, text):
    path = os.path.join(PROJ, relpath)
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old == text:
        return
    changed.append(relpath)
    if not CHECK:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)

def replace_block(relpath, tag, body):
    path = os.path.join(PROJ, relpath)
    src = open(path, encoding="utf-8").read()
    start, end = f"<!-- gen:{tag} -->", f"<!-- /gen:{tag} -->"
    if start not in src or end not in src:
        sys.exit(f"{relpath}: missing markers for {tag}")
    pre, rest = src.split(start, 1)
    _, post = rest.split(end, 1)
    new = f"{pre}{start}\n{STAMP}\n\n{body.rstrip()}\n{end}{post}"
    emit(relpath, new)

def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)

def pinnum(p):
    return 0 if p["pin"] == "STUD" else int(p["pin"])

