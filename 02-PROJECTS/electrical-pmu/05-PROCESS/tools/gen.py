def channels_h():
    outs = [p for p in pins if p["ch"].startswith("O") or p["ch"] in ("A15", "A16")]
    order = {}
    for p in outs:
        n = int(p["ch"][1:]) if p["ch"].startswith("O") else {"A15": 23, "A16": 24}[p["ch"]]
        order[n] = p
    enum_names = ["O1_MOTOR", "O2_HEAD_LO", "O3_HEAD_HI", "O4_DEFOG", "O5_FUEL", "O6_TAIL", "O7_BRAKE", "O8_WIPE_LO", "O9_WIPE_HI", "O10_ACC",
                  "O11_HORN", "O12_IGN", "O13_LS_ECU", "O14_LS_FAN", "O15_COMFORT", "O16_BLOWER", "O17_TURN_L", "O18_TURN_R", "O19_REVERSE",
                  "O20_INTERIOR", "O21_START", "O22_KEEPALIVE", "O23_SPARE", "O24_SPARE"]
    def ca(v):
        try: return int(round(float(v) * 100))
        except: return 0
    default_limit = {"25A": 2500, "15A": 1500, "7A": 700}
    rows = []
    for n in range(1, 25):
        p = order[n]
        steady = ca(p["meas_a"] or p["est_a"])
        if p["soft_fuse"] and p["soft_fuse"] not in ("disabled", "from replacement spec"):
            limit = ca(p["soft_fuse"])          # measured soft fuse wins
        elif p["sim_limit"]:
            limit = int(p["sim_limit"])         # explicit provisional value from the CSV
        else:
            limit = max(100, steady * 2)
        if p["meas_a"]: src = "MEASURED"
        elif p["ch"] == "O16": src = "DEAD"
        elif p["status"] == "RESERVED" or p["ch"] in ("A15", "A16"): src = "RESERVED"
        else: src = "EST"
        name = p["name"].replace("_", " ")
        if p["ch"] in ("A15", "A16"): name = f"{p['ch']} IN"
        rows.append((name, steady, limit, int(p["inrush_x10"] or 10), int(p["inrush_ms"] or 0), src, p["ch"], p["note"].split(".")[0][:28]))
    L = ["/*", " * channels.h — PMU channel table for the simulator", " *",
         " * ============================================================",
         " *  GENERATED by 05-PROCESS/tools/gen.py from 02-HARNESS/data/pmu_pins.csv",
         " *  Do not edit here. Put measured figures in the CSV (meas_a / soft_fuse)",
         " *  and re-run gen.py: this file, CHANNEL-SCHEDULE.md, SPEC.md and the",
         " *  PIN-MAP all update together. That is the whole point.",
         " * ============================================================", " *",
         " * Units: 0.01 A, matching CAN 0x130 and cluster_core.h.",
         " * inrush: multiplier x10 applied for inrushMs after switch-on.",
         " * limit:  measured soft fuse where one exists (D-164/165); otherwise a",
         " *         provisional bench value derived from the estimate. The real",
         " *         PMU output stays DISABLED until measured — this table only",
         " *         drives the simulator and the diagnostics page.",
         " */", "", "#ifndef CHANNELS_H", "#define CHANNELS_H", "", "#include <stdint.h>", "",
         "enum ChSrc : uint8_t { EST = 0, MEASURED = 1, DEAD = 2, RESERVED = 3 };", "",
         "struct ChannelSpec {", "    const char *name;", "    uint16_t    steady;      /* 0.01 A                        */",
         "    uint16_t    limit;       /* 0.01 A soft fuse, provisional */", "    uint8_t     inrushX10;   /* multiplier x10 -> 100 = 10.0x */",
         "    uint16_t    inrushMs;", "    ChSrc       src;", "};", "", "/* ---- O1..O24 ---- */", "static const ChannelSpec CH[24] = {",
         "/*  name            steady  limit  inX10   ms   source      */"]
    for name, steady, limit, ix, ims, src, ch, note in rows:
        L.append(f'  {{ "{name}",'.ljust(22) + f"{steady:5},  {limit:5},  {ix:3}, {ims:4}, {src:<8} }}, /* {ch:<4} {note} */")
    L[-1] = L[-1].replace(" }, /*", " }  /*", 1) if False else L[-1]
    L.append("};")
    L.append("")
    L.append("/* Channel indices, so the model reads like the schedule rather than")
    L.append(" * like an array of magic numbers. O23/O24 are configured as inputs A15/A16. */")
    L.append("enum {")
    L.append("  " + ", ".join(enum_names[0:6]) + ",")
    L.append("  " + ", ".join(enum_names[6:12]) + ",")
    L.append("  " + ", ".join(enum_names[12:16]) + ",")
    L.append("  " + ", ".join(enum_names[16:20]) + ",")
    L.append("  " + ", ".join(enum_names[20:24]))
    L.append("};")
    L.append("")
    L.append("/* How many channel currents are still guesses. Printed at boot so the")
    L.append(" * number in front of you is never mistaken for measured data. */")
    L.append("inline int estimatedChannelCount() {")
    L.append("    int n = 0;")
    L.append("    for (int i = 0; i < 24; i++) if (CH[i].src == EST) n++;")
    L.append("    return n;")
    L.append("}")
    L.append("")
    L.append("#endif /* CHANNELS_H */")
    return "\n".join(L) + "\n"

# -------------------------------------------------------- channel schedule
def schedule_block():
    outs = [p for p in pins if p["ch"].startswith("O") or p["ch"] in ("A15", "A16")]
    key = lambda p: int(p["ch"][1:]) if p["ch"].startswith("O") else {"A15": 23, "A16": 24}[p["ch"]]
    rows = []
    for p in sorted(outs, key=key):
        if p["ch"] in ("A15", "A16"):
            rows.append((f"**O{key(p)}**", f"= **{p['ch']}** input — {p['circuit']}", p["class"], p["to"], p["awg"], "—", "*input*", "input", "**n/a**"))
            continue
        meas = f"**{p['meas_a']} MEAS**" if p["meas_a"] else ("*reserved*" if p["status"] == "RESERVED" else ("**motor is DEAD**" if p["ch"] == "O16" else "______"))
        fuse = f"**{p['soft_fuse']}**" if p["soft_fuse"] else "______"
        rows.append((f"**{p['ch']}**", p["circuit"].split(" — ")[0], p["class"], p["to"], p["awg"], p["est_a"] or "—", meas, p["load_type"], fuse))
    measured = sum(1 for p in outs if p["meas_a"])
    body = md_table(["Ch", "Circuit", "Class", "Goes to", "AWG", "EST A", "**MEASURED A**", "Type", "**SOFT FUSE**"], rows)
    body += f"\n\n**{measured} of 22 outputs measured.** The rest are estimates carried since Rev A."
    return body

