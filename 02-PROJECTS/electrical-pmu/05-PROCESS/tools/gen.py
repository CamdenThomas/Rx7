def cutlist_block():
    hmeta = {h["code"]: h for h in housings}
    byleg = collections.OrderedDict()
    for c in cavs:
        byleg.setdefault(hmeta[c["connector"]]["leg"], []).append(c)
    out = []
    for leg, rows in byleg.items():
        out.append(f"### {leg}\n")
        out.append(md_table(["Cavity", "Circuit", "AWG", "Colour", "Status", "Length", "Qty"],
            [(f"{c['connector']} {c['cav']}", c["circuit"], c["awg"], c["colour"], c["status"], "", 1) for c in rows]))
        out.append("")
    out.append("### Inside the box — PMU pin to receptacle\n")
    out.append("One conductor per PMU cavity to its receptacle(s); split at the busbar where a pin feeds more than one.\n")
    out.append(md_table(["PMU pin", "Ch", "AWG", "Colour", "To", "Length", "Qty"],
        [(p["pin"], p["ch"] if p["ch"] != "—" else p["name"], p["awg"], p["colour"], p["to"], "6–18 in", p["to"].count(" + ") + 1) for p in sorted(pins, key=pinnum) if p["pin"] != "STUD"]))
    return "\n".join(out)

# ------------------------------------------------------------- housings
def housings_block():
    rows = []
    for h in housings:
        n = sum(1 for c in cavs if c["connector"] == h["code"])
        used = sum(1 for c in cavs if c["connector"] == h["code"] and c["status"] != "SPARE")
        rows.append((f"**{h['code']}**", h["leg"], h["class"], h["leg_side"], h["box_side"], h["cavities"], used, h["wedgelocks"], h["where"]))
    t = md_table(["Code", "Leg", "Class", "Leg side", "Box side", "Cav", "Used", "Wedgelocks", "Where"], rows)
    legs = sum(1 for h in housings if h["leg"].startswith("L") and "sill" not in h["leg"])
    doors = sum(1 for h in housings if "sill" in h["leg"])
    drops = sum(1 for h in housings if h["leg"] == "Drop")
    t += f"\n\n**{legs} leg housings (14 codes — L1-S is two housings), {doors} door sub-connectors, {drops} dash-post drops** — plus DP-BAT, DP-GND and the PMU device connector: **{len(housings) + 3} mated pairs.** Every housing is Deutsch DT (size 16), DTP (size 12) or DTM (size 20). Order 20 % spare contacts and wedgelocks."
    return t

