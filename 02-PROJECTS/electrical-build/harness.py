def subset(M, name):
    """Cut one sheet from the model: its wires, the connectors they touch, per-sheet labels and stubs."""
    spec = SHEETS[name]; S = Sheet(); S.problems = []
    wires = [w for w in M.wires if spec["keep"](w[0], w[6])]
    used = {w[2][0] for w in wires} | {w[3][0] for w in wires} | {st[2][0] for st in spec["stubs"]}
    for n, c in M.conn.items():
        if n not in used: continue
        c2 = {k: (list(v) if isinstance(v, list) else v) for k, v in c.items()}
        if n in spec["foreign"]: c2["subtype"] = spec["foreign"][n]
        if spec["leg_labels"] and not n.startswith("DP-") and any((n, p) in M.srcl for p in c2["pins"]):
            c2["labels"] = [f"{lab}  ⟵ {M.srcl[(n, p)]}" if (n, p) in M.srcl else lab for p, lab in zip(c2["pins"], c2["labels"])]
        S.conn[n] = c2
    for sid, text, ep, ga, col, tag in spec["stubs"]:
        S.connector(sid, text, "see the other sheet", simple=True)
        wires.append(("BACKBONE", ga, (sid, None), ep, col, tag, tag))
    if name.startswith("LEG-") and name != "HARNESS":
        # on a leg sheet the housing pins that only exist on the node side would be orphans: hide nothing, WireViz draws them grey
        pass
    # bundles per housing, not per zone: node conductors group by the housing they land on, leg conductors by the
    # housing they leave — small bundle nodes that sit beside their housing, far fewer crossings (D-276)
    regrouped = []
    for w in wires:
        g, a, b = w[0], w[2], w[3]
        if g in ("DASH-NODE", "SILL-NODE"): g = f"{g} → {b[0]}"
        elif g.startswith("LEG-"): g = f"{a[0]} leg" if a[0] in M.conn and not a[0].startswith(("K", "DV", "FAR")) else g
        regrouped.append((g,) + tuple(w[1:]))
    S.wires = regrouped
    return S


def _hash(p):
    return hashlib.sha1(p.read_bytes()).hexdigest()[:12]


def status_line():
    """For {{harness_status}} — are the drawings current with the data?"""
    stale, cur = [], []
    for name in SHEETS:
        y, svg, stamp = OUT / f"{name}.yml", OUT / f"{name}.svg", OUT / f"{name}.stamp"
        if not y.exists(): return "**No harness sheets yet** — run `build`."
        h = _hash(y)
        (cur if svg.exists() and stamp.exists() and stamp.read_text().strip() == h else stale).append(f"`{name}`")
    if not stale: return f"All six sheets are rendered from the current data (`{_hash(OUT / 'HARNESS.yml')}`)."
    return f"**STALE — not re-rendered: {', '.join(stale)}** — install Graphviz and `pip install wireviz` on this machine, then `build` again."


def _renderer():
    if not shutil.which("dot"):  # Graphviz's winget / MSI install does not always reach PATH
        for cand in (r"C:\Program Files\Graphviz\bin", r"C:\Program Files (x86)\Graphviz\bin", str(Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Graphviz" / "bin")):
            if (Path(cand) / "dot.exe").exists():
                os.environ["PATH"] = cand + os.pathsep + os.environ.get("PATH", ""); break
    try:
        from wireviz import wireviz as wv
    except ImportError:
        return None
    return wv if shutil.which("dot") else None


def pre_build(project, db):
    OUT.mkdir(parents=True, exist_ok=True)
    M = build_sheet()
    lines = [f"harness: {len(M.conn)} connectors · {len(M.wires)} conductors in the model"]
    for p in M.problems: lines.append(f"harness: {p}")
    wv = _renderer(); todo = []
    for name, spec in SHEETS.items():
        S = subset(M, name)
        y = OUT / f"{name}.yml"; y.write_text(S.yaml(f"RX-7 FB — electrical build · {spec['title']}", f"Rendered from data/ by tools/rx7.py build (D-275, D-276)", spec["splines"]), encoding="utf-8", newline="\n")
        h = _hash(y); stamp = OUT / f"{name}.stamp"
        if stamp.exists() and stamp.read_text().strip() == h and (OUT / f"{name}.svg").exists(): continue
        todo.append((name, y, h, stamp, len(S.conn), len(S.wires)))
    if not todo:
        lines.append("harness: all six drawings already current"); return lines
    if wv is None:
        lines.append(f"harness: !! NOT RENDERED ({', '.join(t[0] for t in todo)}) — needs Graphviz (dot on PATH) and `pip install wireviz`; marked STALE"); return lines
    for name, y, h, stamp, nc, nw in todo:
        try:
            wv.parse(y, output_formats=("html", "svg"), output_dir=OUT, output_name=name)
        except Exception as e:  # noqa: BLE001 — a rendering failure must be loud, not fatal to the build
            lines.append(f"harness: !! wireviz failed on {name} — {str(e)[:140]}"); continue
        stamp.write_text(h); lines.append(f"harness: rendered {name}.svg + .html — {nc} connectors · {nw} conductors ({h})")
    return lines


